export const DICTIONARIES: Record<Locale, Record<MsgKey, string>> = { en, zh }

export type Params = Record<string, string | number>

export function translate(locale: Locale, key: MsgKey, params?: Params): string {
  const s = DICTIONARIES[locale][key] ?? DICTIONARIES.en[key] ?? key
  return params ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : s
}

/** Plural-aware lookup: `${base}.one` when n === 1, else `${base}.other`; `{n}` is filled in. */
export function translatePlural(locale: Locale, base: string, n: number, params?: Params): string {
  const key = `${base}.${n === 1 ? 'one' : 'other'}` as MsgKey
  return translate(locale, key, { n: formatNumber(locale, n), ...params })
}

export function intlTag(locale: Locale): string {
  return locale === 'zh' ? 'zh-CN' : 'en-US'
}

const numberFormats = new Map<Locale, Intl.NumberFormat>()
export function formatNumber(locale: Locale, n: number): string {
  let f = numberFormats.get(locale)
  if (!f) numberFormats.set(locale, (f = new Intl.NumberFormat(intlTag(locale))))
  return f.format(n)
}

// ───────────── store ─────────────

function detectLocale(): Locale {
  try {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : null
    if (saved === 'en' || saved === 'zh') return saved
  } catch {
    // storage blocked: fall through to the browser language
  }
  const nav = typeof navigator !== 'undefined' ? (navigator.languages?.[0] ?? navigator.language ?? '') : ''
  return /^zh\b/i.test(nav) ? 'zh' : 'en'
}

let current: Locale = detectLocale()
const listeners = new Set<() => void>()

function applyDocumentLang(l: Locale) {
  if (typeof document !== 'undefined') document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
}
applyDocumentLang(current)

export function getLocale(): Locale {
  return current
}

export function setLocale(l: Locale) {
  if (l === current) return
  current = l
  try {
    localStorage.setItem(STORAGE_KEY, l)
  } catch {
    // not persisted (private mode); the choice still applies to this tab
  }
  applyDocumentLang(l)
  for (const fn of listeners) fn()
}

function subscribe(fn: () => void) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

/** Non-React callers (d3 tooltip, formatters) read the current locale directly. */
export function t(key: MsgKey, params?: Params): string {
  return translate(current, key, params)
}
export function tn(base: string, n: number, params?: Params): string {
  return translatePlural(current, base, n, params)
}

/** Re-renders the component when the language changes. */
export function useI18n() {
  const locale = useSyncExternalStore(subscribe, getLocale, () => 'en' as Locale)
  return useMemo(
    () => ({
      locale,
      t: (key: MsgKey, params?: Params) => translate(locale, key, params),
      tn: (base: string, n: number, params?: Params) => translatePlural(locale, base, n, params),
      num: (n: number) => formatNumber(locale, n),
      setLocale,
    }),
    [locale],
  )
}
